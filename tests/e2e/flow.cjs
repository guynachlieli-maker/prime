const { chromium } = require('playwright');
const SHOTS = process.argv[2];
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  const shot = (n) => page.screenshot({ path: `${SHOTS}/${n}.png`, fullPage: false });
  const click = (t) => page.getByRole('button', { name: t, exact: true }).first().click();
  await page.goto('http://localhost:4173');
  await page.fill('input', 'גיא');
  await shot('01-welcome');
  await click('בוא נתחיל');
  await page.getByText('ירידה בשומן').first().click();
  await shot('02-goal');
  await click('המשך');
  await page.getByRole('radio', { name: 'זכר' }).click();
  const inputs = page.locator('input[inputmode="decimal"]');
  await inputs.nth(0).fill('32');
  await inputs.nth(1).fill('180');
  await inputs.nth(2).fill('86');
  await shot('03-body');
  await click('המשך');
  await shot('04-screening');
  await click('המשך');
  await shot('05-activity');
  await click('המשך');
  await page.getByRole('button', { name: 'בוטנים' }).click();
  await page.getByRole('button', { name: 'אבקת חלבון (מי גבינה)' }).click();
  await page.getByRole('button', { name: 'קריאטין' }).click();
  await shot('06-prefs');
  await click('המשך');
  // target weight + date
  await page.locator('input[inputmode="decimal"]').first().fill('76');
  await page.getByText('יש לי תאריך יעד').click();
  await page.locator('input[type="date"]').fill(new Date(Date.now() + 10 * 7 * 864e5).toISOString().slice(0, 10));
  await page.waitForTimeout(200);
  await shot('06b-target');
  const insight = await page.locator('.insight').innerText();
  if (!/הקצב הבטוח/.test(insight)) errors.push('expected unsafe-date insight, got: ' + insight);
  await click('המשך');
  await page.waitForTimeout(1800);
  await shot('07-discovery');
  await page.getByRole('button', { name: 'חודש', exact: true }).first().click();
  await page.waitForTimeout(900);
  await shot('07b-journey-month');
  await page.getByRole('button', { name: 'ביעד', exact: true }).first().click();
  await page.waitForTimeout(900);
  await page.locator('.journey').scrollIntoViewIfNeeded();
  await shot('07c-journey-goal');
  await click('המשך');
  await shot('08-plan');
  await click('יאללה, מתחילים');
  await page.waitForTimeout(900);
  await shot('09-tour1');
  for (let i = 0; i < 4; i++) { await click('הבא'); await page.waitForTimeout(350); }
  await shot('10-tour-last');
  await click('דילוג');
  // Today
  await page.getByRole('button', { name: 'היום', exact: true }).last().click();
  await page.waitForTimeout(300);
  await shot('11-today');
  if (!(await page.getByText('התוספים שלי היום').count())) errors.push('supplements card missing');
  await page.locator('.supp-today button', { hasText: 'קריאטין' }).click();
  await page.locator('.supp-today').scrollIntoViewIfNeeded();
  await shot('11b-supps');
  await page.getByRole('button', { name: /למה\? יעד חלבון/ }).first().click();
  await shot('12-why');
  await page.keyboard.press('Escape');
  await click('אכלתי בדיוק את זה');
  await page.waitForTimeout(200);
  await shot('13-today-after');
  // capture search
  await page.locator('.tab-camera').click();
  await page.getByRole('radio', { name: 'חיפוש' }).click();
  await page.fill('input.search', 'חומוס');
  await page.waitForTimeout(200);
  await shot('14-search');
  await page.locator('.result').first().getByRole('button', { name: '+' }).click();
  await page.getByRole('radio', { name: 'מילים' }).click();
  await page.fill('textarea', 'אכלתי שתי ביצים, פרוסה לחם מלא וחצי פיתה');
  await click('לזהות');
  await page.waitForTimeout(200);
  await shot('15-basket');
  const basketNames = await page.locator('.basket-list strong').allTextContents();
  console.log('BASKET', basketNames.join(' | '));
  await click('אישור ורישום');
  // menu
  await page.locator('.tab-menu').click();
  await page.waitForTimeout(300);
  await shot('16-menu');
  await page.getByRole('button', { name: 'החלפת מנה' }).first().click();
  await shot('17-swap');
  await page.keyboard.press('Escape');
  await click('רשימת קניות');
  await shot('18-shop');
  await page.keyboard.press('Escape');
  // profile -> reminders
  await page.getByRole('button', { name: 'פרופיל והגדרות' }).click();
  await page.waitForTimeout(200);
  await shot('18b-profile');
  await page.locator('.card', { hasText: 'תזכורות והתראות' }).getByRole('button', { name: 'ניהול' }).click();
  await page.fill('input[placeholder^="למשל: לקחת"]', 'לקחת ויטמין D');
  await click('הוספה');
  await page.waitForTimeout(200);
  if (!(await page.getByText('לקחת ויטמין D').count())) errors.push('custom reminder not added');
  await shot('18c-reminders');
  await click('חזרה');
  // progress
  await page.locator('.tab-progress').click();
  await page.waitForTimeout(2000);
  await shot('19-progress');
  await page.mouse.wheel(0, 700);
  await page.waitForTimeout(300);
  await shot('20-progress-chart');
  await page.locator('.tab-menu').click();
  await click('תוכניות ומאמרים');
  await page.waitForTimeout(300);
  await shot('21-programs');
  // ---------- training ----------
  await page.locator('.tab-training').click();
  await page.waitForTimeout(400);
  await shot('30-training-setup');
  await page.getByRole('button', { name: /הגדלת שריר/ }).click();
  await page.getByRole('radio', { name: '4 בשבוע' }).click();
  await page.getByRole('radio', { name: '60 דק׳' }).click();
  await page.getByRole('button', { name: 'ברכיים' }).click();
  await click('בניית התוכנית');
  await page.waitForTimeout(700);
  await shot('31-training-plan');
  await page.mouse.wheel(0, 900);
  await page.waitForTimeout(300);
  await shot('32-training-week');
  await page.mouse.wheel(0, -2000);
  await click('להתחיל אימון');
  await page.waitForTimeout(500);
  await shot('33-session');
  await page.locator('.sets input[inputmode="decimal"]').first().fill('40');
  await page.locator('.set-check').first().click();
  await page.waitForTimeout(400);
  if (!(await page.locator('.rest-timer').count())) errors.push('rest timer did not start');
  await shot('34-session-rest');
  await page.locator('.ex-actions .icon-btn').first().click();
  await page.waitForTimeout(1500);
  await shot('35-exercise-detail');
  await page.keyboard.press('Escape');
  await click('סיום ושמירה');
  await page.waitForTimeout(400);
  await page.getByRole('radio', { name: 'תרגילים' }).click();
  await page.waitForTimeout(1500);
  await page.fill('input.search', 'חזה');
  await page.waitForTimeout(300);
  const libCount = await page.locator('.lib-list li').count();
  if (libCount < 5) errors.push('library search returned ' + libCount);
  await shot('36-library');
  await page.getByRole('radio', { name: 'התקדמות' }).click();
  await page.waitForTimeout(300);
  await shot('37-training-progress');
  await page.locator('.tab-today').click();
  await page.waitForTimeout(300);
  await shot('23-today-demo');
  console.log('ERRORS', JSON.stringify(errors, null, 1));
  await browser.close();
})().catch((e) => { console.error('FAILED', e.message); process.exit(1); });
